/**
 * إضافة تشكيل للكلمات في النص مع الحفاظ على التنسيق
 */
export function vocalizeText(text: string, options: {
  vocalizeAll?: boolean;
  preserveExisting?: boolean;
} = {}): string {
  if (!text || typeof text !== 'string') return text;
  
  // إذا كان النص يحتوي على تشكيل بالفعل
  if (options.preserveAll !== false && /[\u064B-\u065F]/.test(text)) {
    return text;
  }
  
  return addArabicVowels(text);
}

/**
 * إزالة التشكيل من النص العربي
 */
export function removeArabicVowels(text: string): string {
  if (!text) return text;
  
  // إزالة علامات التشكيل
  return text.replace(/[\u064B-\u065F\u0670]/g, '');
}

/**
 * التحقق مما إذا كان النص يحتوي على تشكيل
 */
export function hasArabicVowels(text: string): boolean {
  return /[\u064B-\u065F]/.test(text);
}

/**
 * تنسيق النص العربي مع التشكيل للعرض
 */
export function formatArabicText(text: string, showVowels: boolean = true): string {
  if (!text) return text;
  
  if (showVowels) {
    return vocalizeText(text);
  }
  
  return removeArabicVowels(text);
}

/**
 * إضافة تشكيل للكلمات المفتاحية في النص
 */
export function highlightAndVocalizeKeywords(
  text: string, 
  keywords: string[], 
  showVowels: boolean = true
): { text: string; highlightedCount: number } {
  let result = text;
  let count = 0;
  
  for (const keyword of keywords) {
    const vocalizedKeyword = showVowels ? addArabicVowels(keyword) : keyword;
    const regex = new RegExp(`\\b${keyword}\\b`, 'g');
    
    if (regex.test(result)) {
      result = result.replace(regex, `<span class="text-primary font-semibold">${vocalizedKeyword}</span>`);
      count++;
    }
  }
  
  return { text: result, highlightedCount: count };
}

